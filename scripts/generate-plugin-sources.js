/** Embed source text as ordinary ESM so Node, Bun, and browsers share one catalog. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const references = ["plugins/bundled.js", "bin/web-page.js"].flatMap((file) =>
    [...readFileSync(path.join(root, file), "utf8").matchAll(/pluginSources\[['"]([^'"]+)['"]\]/g)].map((match) => match[1]));
const sources = Object.fromEntries([...new Set(references)].sort().map((file) =>
    [file, readFileSync(path.join(root, "plugins", file), "utf8")]));
const target = path.join(root, "plugins/generated/rix-sources.js");
const content = `// Generated by scripts/generate-plugin-sources.js; edit the original .rix files.\nexport const pluginSources = Object.freeze(${JSON.stringify(sources, null, 2)});\n`;
if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
        throw new Error("Bundled RiX sources are stale; run bun run build:plugin-sources");
    }
} else {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
}
console.log(`Verified ${Object.keys(sources).length} portable plugin sources.`);

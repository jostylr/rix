import { expect, test } from "bun:test";
import { Context, createDefaultRegistry, createDefaultSystemContext, parseAndEvaluate, formatValue } from "../../src/index.js";
import { createPublicationPlan, withPublicationPlan, quartoProjectYaml } from "../../src/runtime/publication-plan.js";
import { encodeOutputJSON, decodeOutputJSON } from "../../src/runtime/output-json.js";
import { renderLatex } from "../../plugins/renderers/document-renderers.js";
const runtime=()=>({context:new Context(),registry:createDefaultRegistry(),systemContext:createDefaultSystemContext()});
export const reportSource=`
    .Plugin.Load("document");
    header := .document.Header(.Paragraph("Publication study"));
    footer := .document.Footer(.Paragraph("Exact sources retained"));
    table := .document.Label("values",.Table(["x","f(x)"],[[1,1/3],[2,2/3],[3,1],[4,4/3]]));
    graphic := .Graphics.Graphic([160,80],[.Graphics.Circle([80,40],20,{= fill="#275dad" })]);
    report := .document.Report("Publication",[.Paragraph("Two columns share one retained tree."),table,.document.Label("diagram",.Figure(graphic,"Exact circle"))],{= header=header,footer=footer });
    plan := .document.PublicationPlan({= columns=2,longTableRows=3,theme=:compact,index=[{= term="Values",label="values"},{= term="Circle",label="diagram"}],requires=["tagged-pdf"] });
    report := .document.Publish(report,plan);
`;
test("publication plans round-trip over an unchanged exact content tree",()=>{
    const state=runtime(),report=parseAndEvaluate(reportSource+"report;",state);
    const original=report.children;
    expect(withPublicationPlan(report,{columns:3}).children).toBe(original);
    const loaded=decodeOutputJSON(encodeOutputJSON(report)).value;
    expect(loaded.publicationPlan.columns).toBe(2);
    expect(loaded.publicationPlan.index.map(x=>x.term)).toEqual(["Circle","Values"]);
    const values=loaded.children.find(x=>x.kind==="table").rows;
    expect(values[0][1].toString()).toBe("1/3");
    expect(()=>createPublicationPlan({columns:5})).toThrow("within");
    expect(()=>createPublicationPlan({schema:"future"})).toThrow("version");
    expect(()=>createPublicationPlan({index:Array(501).fill({term:"x",label:"y"})})).toThrow("budget");
    expect(()=>withPublicationPlan(report,{index:[{term:"missing",label:"missing"}]})).toThrow("does not exist");
});
test("article layout negotiates columns, repeated table headers, running regions, indexes and conformance diagnostics",()=>{
    const state=runtime(),report=parseAndEvaluate(reportSource+"report;",state);
    const latex=renderLatex(report,{format:formatValue,outputTarget:"pdf"});
    expect(latex.content).toContain("\\documentclass[letterpaper]{article}");
    expect(latex.content).toContain("\\begin{multicols}{2}");
    expect(latex.content).toContain("\\begin{longtable}{ll}");
    expect(latex.content).toContain("\\endfirsthead");expect(latex.content).toContain("\\endhead");
    expect(latex.content).toContain("\\fancyhead[L]{Publication study}");
    expect(latex.content).toContain("\\section*{Index}");
    expect(latex.content).toContain("\\pageref*{values}");
    expect(latex.metadata.packages).toEqual(expect.arrayContaining(["longtable","multicol","fancyhdr"]));
    expect(latex.diagnostics.some(d=>d.code==="publication-pdf-conformance-unverified")).toBe(true);
    const exports=parseAndEvaluate('.Plugin.Load("html");.Plugin.Load("quarto");[.html.Render(report),.quarto.Render(report)];',state).values;
    expect(exports[0].entries.get("content").value).toContain('aria-label="Index"');
    expect(exports[1].entries.get("content").value).toContain("column-count:2");
    expect(exports[1].entries.get("content").value).toContain("[Circle](#diagram)");
});
test("explicit slide plans lower through Beamer and RevealJS with bounded table continuation",()=>{
    const state=runtime();
    const deck=parseAndEvaluate(reportSource+`.document.Publish(.Slides([.Slide(.Fragment([.Paragraph([1/3]),table]),"Evidence"),.Slide(.Figure(graphic,"Exact circle"),"Diagram")]),{= profile=:slides,longTableRows=3 });`,state);
    const latex=renderLatex(deck,{format:formatValue});
    expect(latex.content).toContain("\\documentclass[aspectratio=169]{beamer}");
    expect(latex.content).toContain("\\begin{frame}[fragile,allowframebreaks]{Evidence}");
    expect(latex.content).toContain("\\framebreak");
    state.context.set("deck",deck);
    const quarto=parseAndEvaluate('.Plugin.Load("quarto");.quarto.Render(deck).Get("content");',state).value;
    expect(quarto).toContain('format: "revealjs"');expect(quarto).toContain("width: 1280");
    expect(()=>withPublicationPlan(parseAndEvaluate('.Paragraph("body");',state),{profile:"slides"})).toThrow("explicit");
});
test("book/site project sources share Notebook YAML conventions and validate cross-document labels",()=>{
    const state=runtime();
    const project=parseAndEvaluate(`.Plugin.Load("document");.Plugin.Load("quarto");
        first := .Fragment([.Heading(1,"Introduction","intro"),.Paragraph(.Link("chapters/details.qmd#detail","Details"))]);
        second := .Fragment([.Heading(1,"Details","detail"),.Paragraph(.Link("../index.qmd#intro","Introduction"))]);
        project := .document.Project([{= path="index.qmd",title="Introduction",value=first },{= path="chapters/details.qmd",title="Details",value=second }],{= type=:book,title="Study" });
        .quarto.Render(project);`,state);
    const assets=project.entries.get("assets").values;
    const names=assets.map(x=>x.entries.get("path").value);
    expect(names).toContain("index.qmd");expect(names).toContain("chapters/details.qmd");
    const yaml=assets.find(x=>x.entries.get("path").value==="_quarto.yml").entries.get("content").value;
    expect(yaml).toBe(quartoProjectYaml("Study",[{path:"index.qmd"},{path:"chapters/details.qmd"}],{type:"book"}));
    expect(yaml).toContain("book:\n");expect(yaml).toContain("chapters:");
    expect(()=>parseAndEvaluate('.document.Project([{= path="index.qmd",value=first }]);',state)).toThrow("unresolved");
    expect(()=>quartoProjectYaml("Study",[{path:"../outside.qmd"}])).toThrow("unsafe");
});
